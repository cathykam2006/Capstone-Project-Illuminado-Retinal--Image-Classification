"""
Builds the browser-only (GitHub Pages) copy of the Iluminado demo.

TensorFlow Lite can't run in a web browser, so this writes:
  models_numpy/            the two models as plain numpy graphs (export_numpy_models.py)
  app/streamlit_app_static.py  a copy of app/streamlit_app.py whose load_model()
                           uses tflite_numpy.Model instead of TensorFlow Lite
and copies the small files the app reads (model configs, sample images, the
iluminado preprocessing code). Nothing else in the app changes.

Run it from this branch's folder after the app or the models change on main:

    pip install tflite numpy
    python build_static.py /path/to/main/checkout
    python check_numpy_models.py /path/to/main/checkout   # needs ai-edge-litert
"""
import os
import runpy
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = Path(sys.argv[1] if len(sys.argv) > 1 else "../Capstone-Project-Illuminado-Retinal--Image-Classification")

sys.argv = [sys.argv[0], str(SRC)]
runpy.run_path(str(HERE / "export_numpy_models.py"), run_name="__main__")

for rel in ["iluminado/__init__.py", "iluminado/data.py",
            "models/binary_ensemble.json", "models/multilabel_ensemble.json"]:
    (HERE / rel).parent.mkdir(parents=True, exist_ok=True)
    shutil.copy(SRC / rel, HERE / rel)
shutil.rmtree(HERE / "app" / "samples", ignore_errors=True)
shutil.copytree(SRC / "app" / "samples", HERE / "app" / "samples")

app = (SRC / "app" / "streamlit_app.py").read_text()
old = ('    from ai_edge_litert.interpreter import Interpreter\n\n'
       '    runner = Interpreter(model_path=str(tflite), num_threads=2).get_signature_runner()\n')
new = ('    from tflite_numpy import Model   # browser copy: numpy runner, see build_static.py\n\n'
       '    runner = Model(ROOT / "models_numpy" / f"{task}.json", ROOT / "models_numpy" / f"{task}.npz")\n')
if app.count(old) != 1:
    sys.exit("app/streamlit_app.py changed: could not find the TensorFlow Lite loader")
app = app.replace(old, new)
old_check = '    if not cfg.get("tflite") or not tflite.exists():\n'
new_check = '    if not cfg.get("tflite") or not (ROOT / "models_numpy" / f"{task}.npz").exists():\n'
if app.count(old_check) != 1:
    sys.exit("app/streamlit_app.py changed: could not find the model file check")
app = app.replace(old_check, new_check)

header = ('# GENERATED by build_static.py from app/streamlit_app.py on main: do not edit by hand.\n'
          '# Browser (stlite) copy that runs the models with numpy instead of TensorFlow Lite.\n')
(HERE / "app" / "streamlit_app_static.py").write_text(header + app)
print("wrote app/streamlit_app_static.py")
